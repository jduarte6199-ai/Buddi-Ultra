    private func doOpen() {
        guard vm.notchState == .closed else { return }
        withAnimation(animationSpring) {
            vm.open()
        }
    }

    // MARK: - Hover Management

    private func handleHover(_ hovering: Bool) {
        if coordinator.firstLaunch { return }
        hoverTask?.cancel()
        
        if hovering {
            withAnimation(animationSpring) {
                isHovering = true
            }
            
            if vm.notchState == .closed && Defaults[.enableHaptics] {
                haptics.toggle()
            }
            
            guard vm.notchState == .closed,
                  !coordinator.sneakPeek.show,
                  Defaults[.openNotchOnHover] else { return }
            
            hoverTask = Task {
                try? await Task.sleep(for: .seconds(Defaults[.minimumHoverDuration]))
                guard !Task.isCancelled else { return }
                
                await MainActor.run {
                    guard self.vm.notchState == .closed,
                          self.isHovering,
                          !self.coordinator.sneakPeek.show else { return }
                    
                    self.doOpen()
                }
            }
        } else {
            hoverTask = Task {
                try? await Task.sleep(for: .milliseconds(100))
                guard !Task.isCancelled else { return }
                
                await MainActor.run {
                    withAnimation(animationSpring) {
                        self.isHovering = false
                    }
                    
                    if self.vm.notchState == .open && !self.isHovering && !self.vm.isBatteryPopoverActive && !SharingStateManager.shared.preventNotchClose {
                        self.vm.close()
                    }
                }
            }
        }
    }

    // MARK: - Gesture Handling

    private func handleDownGesture(translation: CGFloat, phase: NSEvent.Phase) {
        // Over the music box on the open panel, swipe down = previous media
        // source (mirror of the swipe-up handler: end of gesture, 30pt min).
        if vm.notchState == .open {
            if coordinator.currentView == .home && vm.isHoveringMusicPlayer,
               phase == .ended, translation >= 30 {
                MusicManager.shared.cycleMediaSource(forward: false)
                if Defaults[.enableHaptics] {
                    haptics.toggle()
                }
            }
            return
        }

        guard vm.notchState == .closed else { return }

        if phase == .ended {
            withAnimation(animationSpring) { gestureProgress = .zero }
            return
        }

        withAnimation(animationSpring) {
            gestureProgress = (translation / Defaults[.gestureSensitivity]) * 20
        }

        if translation > Defaults[.gestureSensitivity] {
            if Defaults[.enableHaptics] {
                haptics.toggle()
            }
            withAnimation(animationSpring) {
                gestureProgress = .zero
            }
            doOpen()
        }
    }

    private func handleUpGesture(translation: CGFloat, phase: NSEvent.Phase) {
        guard vm.notchState == .open && !vm.isHoveringCalendar && !vm.isScrollGestureActive else { return }

        // Over the music box a vertical swipe cycles the media source
        // (Now Playing / Apple Music / Spotify / YouTube Music) instead of
        // closing the notch. Swipe up = next source. Fires once per gesture,
        // at gesture end, and only past a real travel threshold so a 4pt
        // trackpad drift can't hop sources.
        if coordinator.currentView == .home && vm.isHoveringMusicPlayer {
            if phase == .ended && translation >= 30 {
                MusicManager.shared.cycleMediaSource(forward: true)
                if Defaults[.enableHaptics] {
                    haptics.toggle()
                }
            }
            return
        }

        withAnimation(animationSpring) {
            gestureProgress = (translation / Defaults[.gestureSensitivity]) * -20
        }

        if phase == .ended {
            withAnimation(animationSpring) {
                gestureProgress = .zero
            }
        }

        if translation > Defaults[.gestureSensitivity] {
            withAnimation(animationSpring) {
                isHovering = false
            }
            if !SharingStateManager.shared.preventNotchClose { 
                gestureProgress = .zero
                vm.close()
            }

            if Defaults[.enableHaptics] {
                haptics.toggle()
            }
        }
    }

    /// Single horizontal two-finger swipe handler for the open panel.
    /// iPhone-style: swiping left slides the content left, so it reveals the tab
    /// on the right (or the next track over the music box); swiping right goes
    /// back. Real horizontal scrollers (calendar day wheel, shelf file strip)
    /// keep the gesture while hovered.
    /// `forward == true` = swipe left (toward the tab on the right / next track).
    private func handleHorizontalSwipe(forward: Bool, phase: NSEvent.Phase) {
        guard phase == .began, vm.notchState == .open else { return }

        // Over the now-playing box on the Dashboard → skip tracks, never tabs.
        if coordinator.currentView == .home && vm.isHoveringMusicPlayer {
            if forward {
                MusicManager.shared.nextTrack()
            } else {
                MusicManager.shared.previousTrack()
            }
            return
        }

        // Real horizontal scrollers own the gesture while hovered.
        if coordinator.currentView == .home && vm.isHoveringCalendar { return }
        if coordinator.currentView == .shelf && vm.isHoveringShelfScroller { return }

        // Vertical chat scrolls never reach here: the pan monitor requires the
        // horizontal delta to dominate before firing.
        guard let index = tabs.firstIndex(where: { $0.view == coordinator.currentView }) else { return }
        let target = forward ? index + 1 : index - 1
        guard tabs.indices.contains(target) else { return }
        withAnimation(.smooth) {
            coordinator.currentView = tabs[target].view
        }
        if Defaults[.enableHaptics] {
            haptics.toggle()
        }
    }
}

struct FullScreenDropDelegate: DropDelegate {
    @Binding var isTargeted: Bool
    let onDrop: () -> Void

    func dropEntered(info _: DropInfo) {
        isTargeted = true
    }

    func dropExited(info _: DropInfo) {
        isTargeted = false
    }

    func performDrop(info _: DropInfo) -> Bool {
        isTargeted = false
        onDrop()
        return true
    }

}

struct GeneralDropTargetDelegate: DropDelegate {
    @Binding var isTargeted: Bool

    func dropEntered(info: DropInfo) {
        isTargeted = true
    }

    func dropExited(info: DropInfo) {
        isTargeted = false
    }

    func dropUpdated(info: DropInfo) -> DropProposal? {
        return DropProposal(operation: .cancel)
    }

    func performDrop(info: DropInfo) -> Bool {
        return false
    }
}

extension ContentView {
    private func BuddyLiveActivity() -> some View {
        let notchContentHeight = max(0, vm.effectiveClosedNotchHeight - (isHovering ? 0 : 12))
        let sideWidth = max(0, vm.effectiveClosedNotchHeight - 12) + 10
        let centerWidth = vm.closedNotchSize.width + (isHovering ? 8 : 0)
        // Single pass: this view re-renders on every instances publish.
        let sessions = BuddiSessionBridge.shared.sessionMonitor.instances
        var isProcessing = false
        var hasPending = false
        var waitingCount = 0
        for session in sessions {
            if session.phase.isActive { isProcessing = true }
            if session.phase.isWaitingForApproval { hasPending = true }
            if session.phase == .waitingForInput { waitingCount += 1 }
        }
        let hasWaiting = waitingCount > 0

        return HStack(spacing: 0) {
            HStack(spacing: 2) {
                BuddyFaceIcon(fontSize: min(notchContentHeight * 0.4, 9))
                if hasPending {
                    PermissionIndicatorIcon(
                        size: min(notchContentHeight * 0.5, 12),
                        color: TerminalColors.amber
                    )
                }
            }
            .frame(width: sideWidth + (hasPending ? 18 : 0), height: notchContentHeight)

            Rectangle()
                .fill(.black)
                .frame(width: centerWidth, height: notchContentHeight)

            Group {
                if isProcessing || hasPending {
                    ProcessingSpinner()
                } else if hasWaiting {
                    // Unanswered-chats indicator: the count shows how many
                    // sessions are sitting there waiting for a reply.
                    HStack(spacing: 3) {
                        ReadyForInputIndicatorIcon(
                            size: min(notchContentHeight * 0.6, 14)
                        )
                        if waitingCount > 1 {
                            Text("\(waitingCount)")
                                .font(.system(
                                    size: min(notchContentHeight * 0.45, 10),
                                    weight: .semibold,
                                    design: .monospaced
                                ))
                                .foregroundStyle(TerminalColors.green)
                        }
                    }
                }
            }
            .frame(width: sideWidth, height: notchContentHeight)
        }
        .frame(height: vm.effectiveClosedNotchHeight + (isHovering ? 8 : 0), alignment: .center)
    }

    private var hasActiveClaudeSession: Bool {
        BuddiSessionBridge.shared.sessionMonitor.instances.contains { $0.phase.isActive || $0.phase.needsAttention }
    }
}

